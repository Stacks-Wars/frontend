function pick<T extends readonly string[]>(
    list: T,
    exclude?: string
): T[number] {
    const pool = exclude ? list.filter((item) => item !== exclude) : [...list]
    const source = pool.length > 0 ? pool : [...list]
    const index =
        typeof crypto !== "undefined" && "getRandomValues" in crypto
            ? crypto.getRandomValues(new Uint32Array(1))[0] % source.length
            : Math.floor(Math.random() * source.length)
    return source[index] as T[number]
}

export function randomLobbyName(exclude?: string): string {
    const current = exclude?.trim()
    const [adj, noun] = current?.split(/\s+/) ?? []
    return `${pick(ADJECTIVES, adj)} ${pick(NOUNS, noun)}`
}
